def classify_file(relative: str):
    """Return the manifest category metadata for one resource file path."""
    normalized = relative.replace(os.sep, "/")
    for prefix, item_root, category, purpose, required, source_hint, notes in FILE_RULES:
        if normalized == prefix or normalized.startswith(prefix):
            item = os.path.relpath(normalized, item_root).replace(os.sep, "/")
            return category, item, purpose, required, source_hint, notes
    return None


def classify_bundle(relative: str):
    """Return the manifest category metadata for one aggregated model directory."""
    normalized = relative.replace(os.sep, "/").rstrip("/")
    aliases = {
        "resources/models/classifier/encoder": "resources/models/classifier/encoder/checkpoint-18000",
        "resources/models/classifier/model": "resources/models/classifier/model/Ref_Tree_Orf_All_orf_tree_processed_Pool_Mean",
    }
    normalized = aliases.get(normalized, normalized)
    for prefix, category, purpose, required, source_hint, notes in BUNDLE_RULES:
        if normalized == prefix:
            return category, Path(normalized).name, purpose, required, source_hint, notes
    return None


def sha256_file(path, chunk=1024 * 1024):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            block = handle.read(chunk)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def tree_size(path):
    if os.path.isfile(path):
        return os.path.getsize(path)
    total = 0
    for root, _dirs, files in os.walk(path):
        for name in files:
            total += os.path.getsize(os.path.join(root, name))
    return total


def format_row(**kwargs):
    values = [str(kwargs.get(field, "")) for field in FIELDS]
    for value in values:
        if "\t" in value or "\n" in value:
            raise ValueError(f"field contains tab/newline: {value}")
    return "\t".join(values)


def collect_rows(root: Path) -> list[str]:
    rows = []
    for category, rel_path, purpose, required in REPO_FILES:
        path = root / rel_path
        if not path.is_file():
            raise SystemExit(f"missing repository file: {path}")
        rows.append(format_row(
            category=category,
            item=path.name,
            required=required,
            install_path=rel_path,
            purpose=purpose,
            size_bytes=path.stat().st_size,
            sha256=sha256_file(path),
            source_hint="bundled in repository",
            notes="",
        ))

    resource_root = root / "resources"
    bundle_paths = {
        relative for relative, *_ in BUNDLE_RULES
        if not is_bundled_resource(relative)
    }
    if resource_root.is_dir():
        for current, directories, filenames in os.walk(resource_root, followlinks=True):
            current_path = Path(current)
            directories[:] = [
                name for name in directories
                if (current_path / name).relative_to(root).as_posix() not in bundle_paths
            ]
            for name in sorted(filenames):
                path = current_path / name
                if not path.is_file():
                    continue
                relative = path.relative_to(root).as_posix()
                if path.suffix == ".bak" or relative == "resources/phylo/taxonomy/na-daxi.csv":
                    continue
                metadata = classify_file(relative)
                if metadata is None:
                    continue
                category, item, purpose, required, source_hint, notes = metadata
                if is_bundled_resource(relative):
                    source_hint = "bundled in repository"
                    notes = ""
                size = path.stat().st_size
                if size > 1024**3:
                    digest = ""
                    notes = f"{notes}; sha256 empty for large file: verify_after_download"
                else:
                    digest = sha256_file(path)
                rows.append(format_row(
                    category=category,
                    item=item,
                    required=required,
                    install_path=relative,
                    purpose=purpose,
                    size_bytes=size,
                    sha256=digest,
                    source_hint=source_hint,
                    notes=notes,
                ))

    for relative, category, purpose, required, source_hint, notes in BUNDLE_RULES:
        path = root / relative
        installed = path.is_dir()
        if installed and is_bundled_resource(relative):
            source_hint = "bundled in repository"
            notes = ""
        rows.append(format_row(
            category=category,
            item=Path(relative).name,
            required=required,
            install_path=relative,
            purpose=purpose,
            size_bytes=tree_size(path) if installed else "",
            sha256="",
            source_hint=source_hint,
            notes=notes if installed else f"not installed at build time; {notes}",
        ))

    phylo_packages = [
        ("resources/phylo/adapter_dir", "lucaphylo_adapter", "Placement adapters for 24 supergroups"),
        ("resources/phylo/backbone_dir", "lucaphylo_backbone", "Backbone alignments and trees for 24 supergroups"),
        ("resources/phylo/taxonomy", "lucaphylo_taxonomy", "Taxonomy tables for 24 supergroups"),
    ]
    for install_path, category, purpose in phylo_packages:
        if (root / install_path).is_dir():
            continue
        rows.append(format_row(
            category=category,
            item=Path(install_path).name,
            required="required",
            install_path=install_path,
            purpose=purpose,
            size_bytes="",
            sha256="",
            source_hint="release resource package",
            notes="resource package not installed at build time",
        ))

    required_external_files = [
        "resources/rdrp/rdrp_reference.dmnd",
        "resources/rdrp/rdrp_reference.fas",
        "resources/rdrp/rdrp_reference.csv",
        "resources/blastdb/refseq_protein/refseq_protein.dmnd",
        "resources/blastdb/refseq_protein/TAXID_viruses.txt",
        "resources/blastdb/refseq_protein/TAXID_cellular.txt",
    ]
    for prefix in ("silva_ssu", "silva_lsu"):
        for suffix in (
            ".1.bt2", ".2.bt2", ".3.bt2", ".4.bt2", ".rev.1.bt2", ".rev.2.bt2",
        ):
            required_external_files.append(f"resources/rrna/{prefix}{suffix}")
    for relative in required_external_files:
        if (root / relative).is_file():
            continue
        metadata = classify_file(relative)
        if metadata is None:
            continue
        category, item, purpose, required, source_hint, notes = metadata
        rows.append(format_row(
            category=category,
            item=item,
            required=required,
            install_path=relative,
            purpose=purpose,
            size_bytes="",
            sha256="",
            source_hint=source_hint,
            notes=f"not installed at build time; {notes}",
        ))
    return rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(REPO / "resources" / "RESOURCE_MANIFEST.tsv"))
    parser.add_argument("--root", default=str(REPO), help="repository root to scan")
    args = parser.parse_args(argv)

    rows = collect_rows(Path(args.root))
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\t".join(FIELDS) + "\n")
        handle.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} rows to {out_path}")


if __name__ == "__main__":
    main()
